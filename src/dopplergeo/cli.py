def parse_time(v) -> float | None:
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return float(v)
    s = str(v).strip()
    try:
        return float(s)
    except ValueError:
        d = dt.datetime.fromisoformat(s.replace("Z", "+00:00"))
        if d.tzinfo is None:
            raise ValueError(f"audio.start_utc {s!r} has no timezone; give UTC explicitly (suffix Z)")
        return d.timestamp()


def parse_region(s: str) -> tuple[tuple[float, float], float]:
    """'center=LAT,LON,radius_km=R' -> ((lat, lon), radius_m)."""
    try:
        parts = dict(p.split("=", 1) for p in s.replace(" ", "").split(",radius_km="))
    except ValueError:
        parts = {}
    if "center" not in s or "radius_km" not in s:
        raise argparse.ArgumentTypeError("region must look like center=LAT,LON,radius_km=R")
    c = s.split("center=")[1].split(",radius_km=")[0]
    lat, lon = (float(v) for v in c.split(","))
    r = float(s.split("radius_km=")[1])
    del parts
    return (lat, lon), r * 1000.0


def require_authorization(cfg: dict, flag: bool) -> str:
    a = cfg["authorization"]
    if not (flag or a.get("attest_owned_or_authorized")):
        sys.exit(
            "refusing to analyse real audio: dopplergeo may only be used on recordings owned by, or explicitly\n"
            "authorized to, the operator. If that is the case, pass --attest-authorized or set\n"
            "authorization.attest_owned_or_authorized: true in your config. The attestation is recorded in the report."
        )
    who = a.get("operator") or "operator (unnamed)"
    src = "--attest-authorized flag" if flag else "config authorization.attest_owned_or_authorized"
    return (f"The operator ({who}) attested via {src} that the analysed recording is owned by, or explicitly "
            "authorized to, the operator. Analysis of third-party recordings is out of scope.")


def _setup_logging(verbose: bool) -> None:
    logging.basicConfig(level=logging.DEBUG if verbose else logging.INFO,
                        format="%(asctime)s %(levelname)s %(name)s: %(message)s", stream=sys.stderr)


