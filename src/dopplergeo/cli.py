def cmd_synth_demo(args, cfg) -> int:
    from . import synth

    c = config.speed_of_sound(cfg)
    seeds = [int(s) for s in str(args.seeds).split(",")]
    out = Path(args.out)
    rows = []
    for seed in seeds:
        run = out if len(seeds) == 1 else out / f"seed_{seed}"
        fx = run / "fixture"
        truth = synth.make_phase0_fixture(fx, seed, cfg, c)
        df, _ = adsb.ingest(fx / "adsb.jsonl", cfg)
        fl = truth["flights"][0]
        tc = pd.read_csv(fx / f"true_curve_{fl['icao24']}.csv")
        tr = {"lat": truth["observer"]["lat"], "lon": truth["observer"]["lon"], "curves": [(tc.t_rel, tc.f_hz)]}
        rcfg = config.deep_merge(cfg, {"elevation": {"constant_m": truth["observer"]["elev_m"], "dem_path": None}})
        res = pipeline.run_locate(
            fx / "audio.wav", df, (truth["search"]["center_lat"], truth["search"]["center_lon"]),
            truth["search"]["radius_m"], rcfg, run, c, events_spec="whole", time_ref="absolute",
            audio_start=truth["audio"]["start_unix"], truth=tr, command=args.command_line,
            attestation="Synthetic fixture generated by this run (no real recording involved).",
            inputs=[{"name": "adsb (synthetic)", "path": str(fx / "adsb.jsonl"), "sha256": "-"},
                    {"name": "truth", "path": str(fx / "truth.yaml"), "sha256": "-"}],
            title=f"Phase 0 synthetic end-to-end (seed {seed})")
        t = res["truth"]
        rows.append({"seed": seed, "err_m": t["err_m"], "truth_rank_nearest": t["nearest_rank"],
                     "top_score": res["top"]["score"], "truth_score": t["score"],
                     "wall_s": res["timings"]["total"], "pass": t["err_m"] <= 150.0})
        print(f"seed {seed}: #1 error {t['err_m']:.1f} m, report {res['report']}")
    if len(seeds) > 1:
        s = pd.DataFrame(rows)
        (out / "summary.md").write_text("# Phase 0 acceptance summary\n\n```\n" + s.to_string(index=False) + "\n```\n")
        s.to_csv(out / "summary.csv", index=False)
    return 0 if all(r["pass"] for r in rows) else 1


def cmd_ingest(args, cfg) -> int:
    type_db = None
    if args.type_db:
        tdb = pd.read_csv(args.type_db, dtype=str)
        type_db = dict(zip(tdb["icao24"].str.lower(), tdb["type_code"].str.upper()))
    df, stats = adsb.ingest(args.src, cfg, type_db)
    adsb.write_parquet(df, args.out)
    print(yaml.safe_dump({"out": str(args.out), **stats}, sort_keys=False))
    return 0


def _events_arg(args, cfg):
    if args.events:
        return [float(v) for v in args.events.split(",")]
    if cfg["detect"]["manual_times_s"]:
        return [float(v) for v in cfg["detect"]["manual_times_s"]]
    return "auto"


def cmd_measure(args, cfg) -> int:
    from . import audio, measure

    att = require_authorization(cfg, args.attest_authorized)
    c = config.speed_of_sound(cfg)
    x, sr = audio.load_audio(args.audio, int(cfg["audio"]["target_sr"]))
    spec = audio.spectrogram_from_config(x, sr, cfg)
    ev = _events_arg(args, cfg)
    diag = None
    if ev == "auto":
        meas, diag = measure.detect_events(spec, cfg, c)
    else:
        meas = [measure.fit_event(spec, cfg, c, t, manual=True) for t in ev]
    doc = {"audio": str(args.audio), "sha256": audio.sha256(args.audio), "attestation": att,
           "speed_of_sound": c, "detector": diag, "events": [m.to_dict() for m in meas]}
    text = yaml.safe_dump(doc, sort_keys=False)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text)
    print(text)
    return 0 if meas and all(m.success for m in meas) else 1


def cmd_locate(args, cfg) -> int:
    att = require_authorization(cfg, args.attest_authorized)
    c = config.speed_of_sound(cfg)
    center, radius = parse_region(args.region)
    df = adsb.read_table(args.adsb)
    start = parse_time(cfg["audio"]["start_utc"])
    truth = None
    if args.truth_latlon:
        la, lo = (float(v) for v in args.truth_latlon.split(","))
        truth = {"lat": la, "lon": lo}
    res = pipeline.run_locate(args.audio, df, center, radius, cfg, args.out, c, events_spec=_events_arg(args, cfg),
                              audio_start=start, truth=truth, command=args.command_line, attestation=att,
                              inputs=[{"name": "adsb", "path": str(args.adsb), "sha256": _sha(args.adsb)}],
                              title="dopplergeo locate (Phase A)")
    top = res["top"]
    print(f"#1: {top['lat']:.6f}, {top['lon']:.6f} score {top['score']:.1f} combo {top['combo']}")
    if res["truth"]:
        print(f"error vs supplied location: {res['truth']['err_m']:.1f} m")
    print(f"report: {res['report']}")
    return 0


def _sha(p) -> str:
    from .audio import sha256

    p = Path(p)
    return sha256(p) if p.is_file() else "-"


def cmd_locate_area(args, cfg) -> int:
    require_authorization(cfg, args.attest_authorized)
    sys.exit("locate-area (Phase B, search_mode: area) is not built yet: per the build brief it is started only "
             "after Phase A passes on an operator-supplied recording.")


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    p = argparse.ArgumentParser(prog="dopplergeo", description=__doc__)
    p.add_argument("--config", help="YAML config (see config.example.yaml)")
    p.add_argument("-v", "--verbose", action="store_true")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("synth-demo", help="Phase 0 synthetic end-to-end validation")
    s.add_argument("--out", required=True)
    s.add_argument("--seeds", default="1", help="comma-separated fixture seeds")

    s = sub.add_parser("ingest-adsb", help="tar1090 history_*.json / readsb aircraft.json -> unified parquet")
    s.add_argument("--src", required=True)
    s.add_argument("--out", required=True)
    s.add_argument("--type-db", help="optional CSV icao24,type_code to fill missing type codes")

    for name in ("measure", "locate", "locate-area"):
        s = sub.add_parser(name)
        s.add_argument("--audio", required=True)
        s.add_argument("--attest-authorized", action="store_true",
                       help="attest the recording is owned by / authorized to the operator")
        if name in ("measure", "locate"):
            s.add_argument("--events", help="comma-separated heard-CPA times (s from audio start); overrides detection")
        if name == "measure":
            s.add_argument("--out")
        if name == "locate":
            s.add_argument("--region", required=True, help="center=LAT,LON,radius_km=R")
            s.add_argument("--adsb", required=True, help="unified parquet file (or dir of parquet files)")
            s.add_argument("--out", required=True)
            s.add_argument("--truth-latlon", help="LAT,LON of the known recording location (evaluation only)")
        if name == "locate-area":
            s.add_argument("--day", required=True)
            s.add_argument("--bbox", required=True)
            s.add_argument("--adsb", required=True)
            s.add_argument("--out", required=True)

    args = p.parse_args(argv)
    args.command_line = "dopplergeo " + " ".join(shlex.quote(a) for a in argv)
    _setup_logging(args.verbose)
    cfg = config.load_config(args.config)
    np.seterr(invalid="ignore")
    return {"synth-demo": cmd_synth_demo, "ingest-adsb": cmd_ingest, "measure": cmd_measure, "locate": cmd_locate,
            "locate-area": cmd_locate_area}[args.cmd](args, cfg)


if __name__ == "__main__":
    sys.exit(main())
